<?php

namespace App\Console\Commands;

use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Database\Connection;
use Illuminate\Database\Migrations\Migration;
use Illuminate\Database\Migrations\Migrator;
use Illuminate\Support\Facades\DB;

#[Signature('migrations:export-sql
    {--after= : Export only the migrations after this name (the last one already applied)}
    {--batch=1 : Batch number to record in the migrations table}
    {--output= : File to write instead of the standard output}')]
#[Description('Generate a phpMyAdmin-ready SQL script from the migrations, including the migrations table and its records')]
class ExportMigrationSql extends Command
{
    /**
     * Compile each migration without executing it; the Laravel migrations remain the source of truth.
     */
    public function handle(Migrator $migrator): int
    {
        $files = $this->migrationFiles($migrator);

        if ($files === null) {
            $this->components->error('The migration given in --after does not exist.');

            return self::FAILURE;
        }

        $connection = DB::connection();
        $batch = (int) $this->option('batch');

        $lines = [
            '-- FUTNEXIS: generated by "php artisan migrations:export-sql". Review it and take a backup before importing.',
            '-- MariaDB runs each schema change outside a transaction: if a statement fails, stop and restore the backup.',
            'SET NAMES utf8mb4;',
            "SET time_zone = '+00:00';",
            '',
            '-- Preflight: stops the import when the approved collation for email addresses is unavailable.',
            "SELECT 'a' COLLATE utf8mb4_uca1400_as_ci;",
            '',
            ...$this->migrationsTableStatements($migrator, $connection),
        ];

        foreach ($files as $name => $path) {
            $lines[] = '';
            $lines[] = '-- '.$name;

            foreach ($this->upStatements($path, $connection) as $statement) {
                $lines[] = $statement.';';
            }

            $lines[] = sprintf('INSERT INTO `migrations` (`migration`, `batch`) VALUES (%s, %d);', $connection->getPdo()->quote($name), $batch);
        }

        $script = implode(PHP_EOL, $lines).PHP_EOL;

        if ($output = $this->option('output')) {
            file_put_contents($output, $script);
            $this->components->info(count($files).' migrations exported to '.$output);

            return self::SUCCESS;
        }

        $this->output->write($script, false, self::OUTPUT_RAW);

        return self::SUCCESS;
    }

    /**
     * @return array<string, string>|null
     */
    private function migrationFiles(Migrator $migrator): ?array
    {
        $files = $migrator->getMigrationFiles([database_path('migrations')]);
        $after = $this->option('after');

        if ($after === null) {
            return $files;
        }

        if (! array_key_exists($after, $files)) {
            return null;
        }

        return array_slice($files, array_search($after, array_keys($files), true) + 1, preserve_keys: true);
    }

    /**
     * @return array<int, string>
     */
    private function migrationsTableStatements(Migrator $migrator, Connection $connection): array
    {
        $queries = $connection->pretend(fn () => $migrator->getRepository()->createRepository());

        return array_map(
            fn (array $query): string => preg_replace('/^create table /i', 'CREATE TABLE IF NOT EXISTS ', $query['query']).';',
            $queries,
        );
    }

    /**
     * @return array<int, string>
     */
    private function upStatements(string $path, Connection $connection): array
    {
        /** @var Migration $migration */
        $migration = require $path;

        $queries = $connection->pretend(fn () => $migration->up());

        return array_map(
            fn (array $query): string => $connection->getQueryGrammar()->substituteBindingsIntoRawSql($query['query'], $connection->prepareBindings($query['bindings'])),
            $queries,
        );
    }
}
